"""提示词模板 —— 这个项目的灵魂部分。

三件事决定了这整套表情能不能看，全在这个文件里：

**一、角色锚必须逐字复制到每一张。**
模型没有记忆，它认角色的唯一依据是参考图 + 提示词里那段不变的角色描述。
所以 `CHARACTER` 只能出现一次定义，被每一张引用，不允许各张自己改字。

**二、定妆照是唯一参考图，也是整批一致性的唯一来源。**
第一张（定妆照）错了，后面 16 张全跟着错。所以界面上把「先看一眼定妆照」
做成一个可选项 —— 花 20 秒看一眼，比后面重出 16 张便宜得多。

**三、画面内的字是让模型画的，不是脚本加的。**
实测：单行 2~4 个汉字，模型 8/8 全对，字形笔画都对。
所以这里不去做「后期用字体打字」那套 —— 字体的位置、描边、和画面的贴合度
都不如模型自己画。⚠️ 边界是 4 个字：再长就开始缺笔画、错字。

（这条跟年历那件正好相反：年历的日期网格 0/4 全错，必须脚本加字。
结论不是「模型能画几个字」，而是「哪类字能让模型画」。）
"""

# ---------------------------------------------------------------- 固定段

# 角色锚：从这个项目的 8 张表情到横幅，逐字相同的一小段。
# 读者不用改 —— 改的是下面 hero_prompt() 里那句「你的猫长什么样」。
FIXED_POSE = ("它正面站立，双手自然垂在身体两侧，眼睛睁大看向前方，"
              "表情是平静的微笑，全身从头到脚都在画面内。")

# 风格段：逐字相同。「纯绿色背景」是刻意的选择 ——
# 表情包要透明底，但让模型直接给「透明」不可靠，给一块纯色反而抠得干净。
STYLE = ("Q版卡通表情包风格，粗黑描边，扁平明亮配色，高对比，主体居中占满画面，"
         "全身可见，纯绿色背景（嫩绿 #26ED16），画面干净，没有多余装饰。")

# 保特征：这一句是「还是我家那只猫」的关键，实测比不写明显更像。
KEEP = ("请严格保留这只猫的毛色分布、花纹位置和眼睛颜色，画出来的必须还是同一只猫，"
        "不要换一个品种，不要改变花纹。")

NO_TEXT = "画面里没有任何文字。"

NEGATIVE = ("多个角色，两只猫，不同的动物，风格不一致，写实照片，水印，签名，二维码，网址，"
            "多余的文字，错别字，乱码，模糊，低分辨率，白边，位置偏移，大小改变，画面构图改变，"
            "深色背景，白色背景，透明背景")


# ---------------------------------------------------------------- 三种提示词

def hero_prompt(desc="", from_photo=True):
    """定妆照。整套表情的一致性从这里开始。

    `desc` 是读者填的那句「你的猫长什么样」（毛色、花纹、眼睛颜色）。
    照片负责长相，文字负责把它说清楚 —— 两个一起给，比只给一个稳。
    """
    if from_photo:
        head = "Q版卡通表情包角色设定图：把参考照片里的这只猫画成卡通角色。"
    else:
        head = "Q版卡通表情包角色设定图："
    parts = [head]
    if desc.strip():
        parts.append("它是一只%s的小猫。" % desc.strip())
    parts.append(FIXED_POSE)
    if from_photo:
        parts.append(KEEP)
    parts.append(STYLE)
    parts.append(NO_TEXT)
    return "\n\n".join(parts)


def frame_prompt(text, state, desc="", from_photo=True):
    """一张表情。`state` 是这一帧的动作与神态。

    同一条表情的两帧之间：**只有 `state` 那一句不同，其余逐字相同**，
    并额外加一句锁构图的话。这是让 GIF 里「只有该动的地方动了」的唯一办法。
    """
    head = ("Q版卡通表情包：%s\n\n"
            % ("把参考照片里的这只猫画成卡通角色" if from_photo else "一只小猫"))
    if desc.strip():
        head += "它是一只%s的小猫。\n\n" % desc.strip()
    lock = ("严格保持与参考图完全相同的姿势、位置、大小、朝向和画面构图，"
            "只改变下面说明的这一处，其余一切照旧。")
    return ("%s%s\n\n动作与神态：%s。\n\n%s\n\n%s\n"
            "画面下方有一行居中的中文大字「%s」，白色描边黑色字体，"
            "字形完整正确、笔画清晰可读，文字不能遮挡角色的脸，"
            "文字四周要留出空白，不要贴到画面边缘。"
            % (head, lock, state, STYLE, NO_TEXT, text))


def banner_prompt(desc=""):
    """详情页顶部那条横幅 750×400。

    ⚠️ 官方对这条横幅另有三条要求：**避免任何文字、避免白底、避免透明底**。
    所以这里用淡蓝底，负面词里也把「白色背景 / 透明背景 / 文字」全列进去。
    —— 这三条最容易漏，第一版给米白底就是不合格的。
    """
    head = "Q版卡通横幅插画：把参考照片里的这只猫画成卡通角色。"
    d = "它是一只%s的小猫。" % desc.strip() if desc.strip() else ""
    style = ("Q版卡通插画风格，粗黑描边，扁平明亮配色，高对比，淡蓝色纯色背景，"
             "画面干净，留白充足，没有多余装饰。")
    scene = ("它坐在画面中央偏右的位置，侧身回头看过来，眼睛睁大，表情开心，"
             "左侧下方散落着几片小叶子。横版构图，主体与装饰之间留出干净的间隔。")
    return "\n\n".join(x for x in [head, d, scene, KEEP, style, "画面里没有任何文字。"] if x)


